// Writes supabase/seed.sql from the catalog in src/lib/catalog.ts (Appendix A).
//   npm run gen:seed
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATALOG } from '../src/lib/catalog';

const q = (s: string | number | null | undefined) =>
  s === null || s === undefined ? 'null' : typeof s === 'number' ? String(s) : `'${String(s).replace(/'/g, "''")}'`;

const rows = CATALOG.map(
  (i) => `  (${q(i.id)}, ${q(i.kind)}, ${q(i.title)}, ${q(i.year)}, ${q(i.by)}, ${q(i.mins)}, ${q(i.cc)}, ${i.v ? `'{${i.v.join(',')}}'` : 'null'}, ${q(i.log)})`,
);

const sql = `-- Catalog seed (Appendix A). Generated by scripts/gen-seed-sql.ts — do not edit by hand.
-- Heat vectors are sample ratings for the prototype.
insert into public.items (id, kind, title, year, by, mins, cc, v, log) values
${rows.join(',\n')}
on conflict (id) do update set
  kind = excluded.kind, title = excluded.title, year = excluded.year, by = excluded.by,
  mins = excluded.mins, cc = excluded.cc, v = excluded.v, log = excluded.log;
`;

writeFileSync(join(__dirname, '..', 'supabase', 'seed.sql'), sql);
console.log(`Wrote ${CATALOG.length} items to supabase/seed.sql`);
